"""Generates game/src/survivors/armory.rs (TQ2 armour sets and jewelry) and the matching
asset entries in tools/assets.json ("armor" character, item icons) from the TQ2 file list.

Run from the repository root after `Tq2Extract list > cache/filelist.txt`:
    py tools/gen_armory.py
"""
import json
import re

files = open('cache/filelist.txt', encoding='utf8').read().split('\n')
icons = {f.split('/')[-1][:-7] for f in files if '/t_icon_armor_' in f and f.endswith('.uasset')}

SLOTS = ['helmet', 'torso', 'shoulder', 'arm', 'leg']
RUST_SLOT = {'helmet': 'Head', 'torso': 'Chest', 'shoulder': 'Shoulders', 'arm': 'Arms', 'leg': 'Legs'}
# Armour of a full set per weight class, split over the pieces.
SHARE = {'helmet': 0.18, 'torso': 0.34, 'shoulder': 0.16, 'arm': 0.12, 'leg': 0.20}
CLASS_ARMOR = {'light': 0.10, 'medium': 0.20, 'heavy': 0.30}
NOUNS = {
    'light': {'helmet': 'Hood', 'torso': 'Robe', 'shoulder': 'Mantle', 'arm': 'Wraps', 'leg': 'Sandals'},
    'medium': {'helmet': 'Cap', 'torso': 'Jerkin', 'shoulder': 'Shoulderguards', 'arm': 'Bracers', 'leg': 'Boots'},
    'heavy': {'helmet': 'Helm', 'torso': 'Cuirass', 'shoulder': 'Pauldrons', 'arm': 'Vambraces', 'leg': 'Greaves'},
}
# (folder, display name, weight class)
SETS = [
    ('Armor_Greek_Scholar_01', "Acolyte's", 'light'),
    ('Armor_Greek_Scholar_03', "Sage's", 'light'),
    ('Armor_Greek_Scholar_05', "Philosopher's", 'light'),
    ('Armor_Greek_Scholar_07', "Seer's", 'light'),
    ('Armor_Greek_Ranger_03', "Hunter's", 'medium'),
    ('Armor_Greek_Ranger_04', "Scout's", 'medium'),
    ('Armor_Greek_Ranger_06', "Tracker's", 'medium'),
    ('Armor_Greek_Ranger_08', "Pathfinder's", 'medium'),
    ('Armor_Ichthian_Medium', "Ichthian Reaver's", 'medium'),
    ('Armor_Centaur_Light_01', "Centaur Outrider's", 'medium'),
    ('Armor_Greek_Soldier_02', "Hoplite's", 'heavy'),
    ('Armor_Greek_Soldier_03', 'Phalanx', 'heavy'),
    ('Armor_Greek_Soldier_05', "Myrmidon's", 'heavy'),
    ('Armor_Greek_Soldier_09', "Champion's", 'heavy'),
    ('Armor_Centaur_Heavy', "Centaur Warlord's", 'heavy'),
]

JEWELRY = [
    ('ring', 'ring_greek_magic_01', 'Bronze Ring'), ('ring', 'ring_greek_magic_04', 'Signet of Delos'),
    ('ring', 'ring_greek_magic_06', 'Band of Thebes'), ('ring', 'ring_greek_rare_01', 'Ring of the Oracle'),
    ('ring', 'ring_greek_rare_04', "Hermes' Loop"), ('ring', 'ring_greek_rare_06', 'Seal of Minos'),
    ('ring', 'ring_ichthian_magic_01', 'Coral Ring'), ('ring', 'ring_ichthian_rare_01', 'Ring of the Deep'),
    ('amulet', 'necklace_greek_magic_01', 'Bronze Torc'), ('amulet', 'necklace_greek_magic_03', 'Owl Pendant'),
    ('amulet', 'necklace_greek_magic_05', 'Laurel Charm'), ('amulet', 'necklace_greek_rare_01', 'Amulet of Athena'),
    ('amulet', 'necklace_greek_rare_03', 'Eye of Argus'), ('amulet', 'necklace_greek_rare_05', 'Medallion of Ares'),
    ('amulet', 'necklace_greek_rare_08', 'Gorgon Pendant'), ('amulet', 'necklace_ichthian_rare_01', 'Pearl of the Abyss'),
]


def ident(s):
    return re.sub(r'[^A-Z0-9]+', '_', s.upper()).strip('_')


pieces = []
for folder, name, cls in SETS:
    meshes = [f for f in files if f'/Armor/' in f and f'/{folder}/' in f and re.search(r'/sk_(male|human)_(helmet|arm|leg|shoulder|torso)_[^/]+\.uasset$', f)]
    for slot in SLOTS:
        for m in sorted(meshes):
            mesh = m.split('/')[-1][:-7]
            if f'_{slot}_' not in mesh:
                continue
            key = re.sub(r'^sk_(male|human)_' + slot + '_', '', mesh)
            short = re.sub(r'_t\d[ab]?(_v\d)?$|_0\d$', '', key)
            icon = next((c for c in [f't_icon_armor_{slot}_{key}_battlemage_none', f't_icon_armor_{slot}_{key}_none',
                                     f't_icon_armor_{slot}_{short}_battlemage_none', f't_icon_armor_{slot}_{short}_01_battlemage_none'] if c in icons), None)
            if icon:
                pieces.append(dict(folder=folder, set=name, cls=cls, slot=slot, mesh=mesh, path=m, icon=icon))
                break

out = ['//! TQ2 armour sets and jewelry. Generated by tools/gen_armory.py from TQ2 file names; edit',
       '//! the generator (names, weight classes) rather than this file.',
       'use super::equipment::{ArmorDef, ArmorSlot, Item, JewelryDef, JewelryKind};', '']
items = []
for p in pieces:
    cid = ident(f"{p['folder'].replace('Armor_', '')}_{p['slot']}")
    pid = cid.lower()
    armor = round(CLASS_ARMOR[p['cls']] * SHARE[p['slot']], 4)
    out.append(f'pub const {cid}: ArmorDef = ArmorDef {{')
    out.append(f'    id: "{pid}",')
    out.append(f'    name: "{p["set"]} {NOUNS[p["cls"]][p["slot"]]}",')
    out.append(f'    icon: "{p["icon"]}",')
    out.append(f'    slot: ArmorSlot::{RUST_SLOT[p["slot"]]},')
    out.append(f'    parts: &["armor/{p["mesh"]}_animated.glb"],')
    out.append(f'    armor: {armor},')
    out.append('};')
    items.append(f'Item::Armor(&{cid})')
for kind, icon, name in JEWELRY:
    cid = ident(icon)
    value = {'ring': 0.03, 'amulet': 15.0}[kind]
    if 'rare' in icon:
        value = {'ring': 0.05, 'amulet': 25.0}[kind]
    out.append(f'pub const {cid}: JewelryDef = JewelryDef {{')
    out.append(f'    id: "{cid.lower()}",')
    out.append(f'    name: "{name}",')
    out.append(f'    icon: "t_icon_armor_{icon}_battlemage_none",')
    out.append(f'    kind: JewelryKind::{"Ring" if kind == "ring" else "Amulet"},')
    out.append(f'    value: {value},')
    out.append('};')
    items.append(f'Item::Jewelry(&{cid})')
out.append('')
out.append('/// Every generated item.')
out.append('pub const ITEMS: &[Item] = &[')
out += [f'    {i},' for i in items]
out.append('];')
open('game/src/survivors/armory.rs', 'w', encoding='utf8').write('\n'.join(out) + '\n')

a = json.load(open('tools/assets.json', encoding='utf8'))
a['characters']['armor'] = {
    'parts': [p['path'] for p in pieces],
    'skeleton': a['characters']['hero']['skeleton'],
    # The pieces follow the hero's bones at runtime; they need no clips of their own.
    'anims': [],
    'clips': ['__none__'],
}
for p in pieces:
    if p['icon'] not in a['textures']['items']:
        a['textures']['items'].append(p['icon'])
for _, icon, _ in JEWELRY:
    name = f't_icon_armor_{icon}_battlemage_none'
    if name not in a['textures']['items']:
        a['textures']['items'].append(name)
open('tools/assets.json', 'w', encoding='utf8').write(json.dumps(a, indent=2) + '\n')
print(f'{len(pieces)} armour pieces from {len(SETS)} sets, {len(JEWELRY)} jewelry')
